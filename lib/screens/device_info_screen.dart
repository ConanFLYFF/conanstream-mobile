                                  "PAYER 29,99 € VIA PAYPAL",
                                  style: TextStyle(fontWeight: FontWeight.bold, fontSize: 14),
                                ),
                                onPressed: _launchPayPalPayment,
                              ),
                            ),
                            const SizedBox(height: 12),

                            // BOUTON DE DÉBLOCAGE AUTOMATIQUE POST-PAIEMENT
                            SizedBox(
                              width: double.infinity,
                              child: OutlinedButton.icon(
                                style: OutlinedButton.styleFrom(
                                  foregroundColor: Colors.greenAccent,
                                  side: const BorderSide(color: Colors.greenAccent),
                                  padding: const EdgeInsets.symmetric(vertical: 12),
                                  shape: RoundedRectangleBorder(
                                    borderRadius: BorderRadius.circular(10),
                                  ),
                                ),
                                icon: _isVerifyingPayment
                                    ? const SizedBox(
                                        width: 16,
                                        height: 16,
                                        child: CircularProgressIndicator(
                                            strokeWidth: 2, color: Colors.greenAccent),
                                      )
                                    : const Icon(Icons.check_circle_outline, color: Colors.greenAccent),
                                label: const Text(
                                  "J'ai payé, Débloquer à vie",
                                  style: TextStyle(fontWeight: FontWeight.bold, fontSize: 13),
                                ),
                                onPressed: _isVerifyingPayment ? null : _autoActivateAfterPayment,
                              ),
                            ),
                            const SizedBox(height: 16),
                            const Divider(color: Colors.white12),
                            const SizedBox(height: 10),
                          ],

                          // QR Code de paiement
                          Container(
                            padding: const EdgeInsets.all(8),
                            decoration: BoxDecoration(
                              color: Colors.white,
                              borderRadius: BorderRadius.circular(12),
                            ),
                            child: Image.network(
                              "https://api.qrserver.com/v1/create-qr-code/?size=150x150&data=${Uri.encodeComponent(_paypalLink)}",
                              width: 110,
                              height: 110,
                              errorBuilder: (_, __, ___) => const Icon(Icons.qr_code, size: 90, color: Colors.black),
