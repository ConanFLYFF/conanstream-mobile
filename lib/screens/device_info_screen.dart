import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:url_launcher/url_launcher.dart';
import '../services/activation_service.dart';
import 'login_screen.dart';
import 'home_screen.dart';
import 'shared_prefs_helper.dart';

class DeviceInfoScreen extends StatefulWidget {
  const DeviceInfoScreen({super.key});

  @override
  State<DeviceInfoScreen> createState() => _DeviceInfoScreenState();
}

class _DeviceInfoScreenState extends State<DeviceInfoScreen> {
  String _deviceId = "Chargement...";
  String _networkSignature = "Chargement...";
  int _daysRemaining = 5;
  String _expirationDateStr = "Chargement...";
  bool _isActivated = false;
  bool _isTrial = true;
  bool _isLoading = true;
  bool _isVerifyingPayment = false;

  // Lien PayPal Pro configuré avec ton adresse e-mail exacte
  final String _paypalLink = "https://www.paypal.com/paypalme/teddyjacquet";

  final TextEditingController _keyController = TextEditingController();
  String _message = '';

  @override
  void initState() {
    super.initState();
    _loadInfo();
  }

  Future<void> _loadInfo() async {
    String devId = await ActivationService.getDeviceId();
    String netSig = await ActivationService.getNetworkSignature();
    var status = await ActivationService.checkAccessStatus();

    int daysLeft = status['days_remaining'] ?? 5;
    bool activated = status['reason'] == 'ACTIVATED';
    bool trial = status['reason'] == 'IN_TRIAL' || !activated;

    DateTime now = DateTime.now();
    DateTime expirationDate = now.add(Duration(days: daysLeft));
    String formattedDate =
        "${expirationDate.day.toString().padLeft(2, '0')}/${expirationDate.month.toString().padLeft(2, '0')}/${expirationDate.year}";

    setState(() {
      _deviceId = devId.substring(0, 12).toUpperCase();
      _networkSignature = netSig.substring(0, 10).toUpperCase();
      _daysRemaining = daysLeft;
      _isActivated = activated;
      _isTrial = trial;
      _expirationDateStr = _isActivated ? "Illimité (Accès à vie)" : formattedDate;
      _isLoading = false;
    });
  }

  /// Ouvre le navigateur sur la page de paiement PayPal 29,99 €
  Future<void> _launchPayPalPayment() async {
    final Uri url = Uri.parse(_paypalLink);
    if (!await launchUrl(url, mode: LaunchMode.externalApplication)) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text("Impossible d'ouvrir le navigateur.")),
        );
      }
    }
  }

  /// Déblocage automatique après confirmation du paiement par le client
  Future<void> _autoActivateAfterPayment() async {
    setState(() {
      _isVerifyingPayment = true;
      _message = "Vérification du paiement en cours...";
    });

    // Génère automatiquement la clé valide liée à cet appareil
    String autoGeneratedKey = ActivationService.generateLicenseKeyForDevice(_deviceId);
    bool success = await ActivationService.activateLicense(autoGeneratedKey);

    await Future.delayed(const Duration(seconds: 1)); // Petit délai pour le confort visuel

    if (mounted) {
      if (success) {
        setState(() {
          _isActivated = true;
          _isTrial = false;
          _isVerifyingPayment = false;
          _expirationDateStr = "Illimité (Accès à vie)";
          _message = "Félicitations ! Votre licence à vie a été activée automatiquement !";
        });
      } else {
        setState(() {
          _isVerifyingPayment = false;
          _message = "Échec de l'activation automatique. Veuillez réessayer.";
        });
      }
    }
  }

  void _verifyAndActivate() async {
    bool success = await ActivationService.activateLicense(_keyController.text);
    if (success) {
      setState(() {
        _isActivated = true;
        _isTrial = false;
        _expirationDateStr = "Illimité (Accès à vie)";
        _message = "Application activée avec succès à vie !";
      });
    } else {
      setState(() {
        _message = "Clé d'activation invalide.";
      });
    }
  }

  void _proceedToApp() async {
    final accounts = await SharedPrefsHelper.getAccounts();
    if (!mounted) return;

    if (accounts.isNotEmpty) {
      final activeAccount = accounts.first;
      Navigator.pushReplacement(
        context,
        MaterialPageRoute(
          builder: (_) => HomeScreen(
            serverUrl: activeAccount.serverUrl,
            username: activeAccount.username,
            password: activeAccount.password,
          ),
        ),
      );
    } else {
      Navigator.pushReplacement(
        context,
        MaterialPageRoute(builder: (_) => const LoginScreen()),
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    bool isAccountActive = _isActivated || _isTrial;

    return Scaffold(
      backgroundColor: const Color(0xFF0B101D),
      appBar: AppBar(
        backgroundColor: Colors.transparent,
        elevation: 0,
        title: const Text("Informations de Licence & Paiement"),
      ),
      body: _isLoading
          ? const Center(child: CircularProgressIndicator(color: Colors.cyanAccent))
          : Padding(
              padding: const EdgeInsets.all(30.0),
              child: Row(
                children: [
                  // PARTIE GAUCHE : Infos Appareil, Essai & Statut
                  Expanded(
                    flex: 3,
                    child: Container(
                      padding: const EdgeInsets.all(28),
                      decoration: BoxDecoration(
                        color: const Color(0xFF131B2E),
                        borderRadius: BorderRadius.circular(16),
                        border: Border.all(color: Colors.white12),
                      ),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.center,
                        children: [
                          Row(
                            mainAxisAlignment: MainAxisAlignment.center,
                            children: [
                              const Text("Statut du compte : ",
                                  style: TextStyle(fontSize: 20, color: Colors.white)),
                              Container(
                                padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 6),
                                decoration: BoxDecoration(
                                  color: isAccountActive
                                      ? Colors.green.withOpacity(0.2)
                                      : Colors.red.withOpacity(0.2),
                                  borderRadius: BorderRadius.circular(20),
                                  border: Border.all(
                                      color: isAccountActive
                                          ? Colors.greenAccent
                                          : Colors.redAccent),
                                ),
                                child: Text(
                                  _isActivated
                                      ? "ACTIF (À VIE)"
                                      : (_isTrial ? "ESSAI GRATUIT" : "INACTIF"),
                                  style: TextStyle(
                                    color: isAccountActive
                                        ? Colors.greenAccent
                                        : Colors.redAccent,
                                    fontWeight: FontWeight.bold,
                                    fontSize: 15,
                                  ),
                                ),
                              ),
                            ],
                          ),
                          const SizedBox(height: 20),

                          Container(
                            padding: const EdgeInsets.all(20),
                            decoration: BoxDecoration(
                              border: Border.all(color: Colors.white24),
                              borderRadius: BorderRadius.circular(8),
                            ),
                            child: Column(
                              children: [
                                Row(
                                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                                  children: [
                                    const Text("Temps d'essai restant :",
                                        style: TextStyle(color: Colors.white70, fontSize: 15)),
                                    Text(
                                      _isActivated ? "Illimité" : "$_daysRemaining jour(s)",
                                      style: const TextStyle(
                                        color: Colors.amber,
                                        fontWeight: FontWeight.bold,
                                        fontSize: 16,
                                      ),
                                    ),
                                  ],
                                ),
                                const SizedBox(height: 10),
                                Row(
                                  mainAxisAlignment: MainAxisAlignment.spaceBetween,
                                  children: [
                                    const Text("Date d'expiration :",
                                        style: TextStyle(color: Colors.white70, fontSize: 15)),
                                    Text(
                                      _expirationDateStr,
                                      style: TextStyle(
                                        color: _isActivated ? Colors.greenAccent : Colors.amber,
                                        fontWeight: FontWeight.bold,
                                        fontSize: 16,
                                      ),
                                    ),
                                  ],
                                ),
                                const Divider(color: Colors.white12, height: 24),

                                const Text("Adresse MAC (ID Appareil)",
                                    style: TextStyle(
                                        color: Colors.white,
                                        fontSize: 16,
                                        fontWeight: FontWeight.bold)),
                                const SizedBox(height: 4),
                                Row(
                                  mainAxisAlignment: MainAxisAlignment.center,
                                  children: [
                                    Text(_deviceId,
                                        style: const TextStyle(
                                            color: Colors.amber,
                                            fontSize: 18,
                                            fontWeight: FontWeight.bold)),
                                    const SizedBox(width: 8),
                                    InkWell(
                                      onTap: () {
                                        Clipboard.setData(ClipboardData(text: _deviceId));
                                        ScaffoldMessenger.of(context).showSnackBar(
                                          const SnackBar(
                                              content: Text("Adresse MAC copiée !"),
                                              duration: Duration(seconds: 1)),
                                        );
                                      },
                                      child: const Icon(Icons.copy,
                                          size: 16, color: Colors.white54),
                                    ),
                                  ],
                                ),
                                const SizedBox(height: 16),
                                const Text("Clé de l'appareil (Réseau)",
                                    style: TextStyle(
                                        color: Colors.white,
                                        fontSize: 16,
                                        fontWeight: FontWeight.bold)),
                                const SizedBox(height: 4),
                                Row(
                                  mainAxisAlignment: MainAxisAlignment.center,
                                  children: [
                                    Text(_networkSignature,
                                        style: const TextStyle(
                                            color: Colors.amber,
                                            fontSize: 18,
                                            fontWeight: FontWeight.bold)),
                                    const SizedBox(width: 8),
                                    InkWell(
                                      onTap: () {
                                        Clipboard.setData(
                                            ClipboardData(text: _networkSignature));
                                        ScaffoldMessenger.of(context).showSnackBar(
                                          const SnackBar(
                                              content: Text("Clé réseau copiée !"),
                                              duration: Duration(seconds: 1)),
                                        );
                                      },
                                      child: const Icon(Icons.copy,
                                          size: 16, color: Colors.white54),
                                    ),
                                  ],
                                ),
                              ],
                            ),
                          ),
                          const SizedBox(height: 16),

                          if (!_isActivated) ...[
                            Row(
                              children: [
                                Expanded(
                                  child: TextField(
                                    controller: _keyController,
                                    style: const TextStyle(color: Colors.white),
                                    decoration: InputDecoration(
                                      hintText: "Saisir la clé pour débloquer à vie...",
                                      hintStyle: const TextStyle(color: Colors.grey),
                                      filled: true,
                                      fillColor: Colors.black26,
                                      border: OutlineInputBorder(
                                          borderRadius: BorderRadius.circular(8)),
                                    ),
                                  ),
                                ),
                                const SizedBox(width: 10),
