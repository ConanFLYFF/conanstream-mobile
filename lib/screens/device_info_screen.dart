                                      ),
                                    ],
                                  ),
                                  const Divider(color: Colors.white12, height: 20),

                                  const Text("Adresse MAC (ID Appareil)",
                                      style: TextStyle(
                                          color: Colors.white,
                                          fontSize: 15,
                                          fontWeight: FontWeight.bold)),
                                  const SizedBox(height: 4),
                                  Row(
                                    mainAxisAlignment: MainAxisAlignment.center,
                                    children: [
                                      Text(_deviceId,
                                          style: const TextStyle(
                                              color: Colors.amber,
                                              fontSize: 16,
                                              fontWeight: FontWeight.bold)),
                                      const SizedBox(width: 8),
                                      InkWell(
                                        onTap: () {
                                          Clipboard.setData(ClipboardData(text: _deviceId));
                                          ScaffoldMessenger.of(context).showSnackBar(
                                            const SnackBar(
                                                content: Text("Adresse MAC copiée !"),
                                                duration: Duration(seconds: 1)),
                                          );
                                        },
                                        child: const Icon(Icons.copy,
                                            size: 16, color: Colors.white54),
                                      ),
                                    ],
                                  ),
                                  const SizedBox(height: 12),
                                  const Text("Clé de l'appareil (Réseau)",
                                      style: TextStyle(
                                          color: Colors.white,
                                          fontSize: 15,
                                          fontWeight: FontWeight.bold)),
                                  const SizedBox(height: 4),
                                  Row(
                                    mainAxisAlignment: MainAxisAlignment.center,
                                    children: [
                                      Text(_networkSignature,
                                          style: const TextStyle(
                                              color: Colors.amber,
                                              fontSize: 16,
                                              fontWeight: FontWeight.bold)),
                                      const SizedBox(width: 8),
                                      InkWell(
                                        onTap: () {
                                          Clipboard.setData(
                                              ClipboardData(text: _networkSignature));
                                          ScaffoldMessenger.of(context).showSnackBar(
                                            const SnackBar(
                                                content: Text("Clé réseau copiée !"),
                                                duration: Duration(seconds: 1)),
                                          );
                                        },
                                        child: const Icon(Icons.copy,
                                            size: 16, color: Colors.white54),
                                      ),
                                    ],
                                  ),
                                ],
                              ),
                            ),
                            const SizedBox(height: 14),

                            if (!_isActivated) ...[
                              Row(
                                children: [
                                  Expanded(
                                    child: TextField(
                                      controller: _keyController,
                                      style: const TextStyle(color: Colors.white),
                                      decoration: InputDecoration(
                                        hintText: "Saisir la clé pour débloquer à vie...",
                                        hintStyle: const TextStyle(color: Colors.grey),
