                                  label: const Text(
                                    "PAYER 5,00 € VIA PAYPAL",
                                    style: TextStyle(fontWeight: FontWeight.bold, fontSize: 13),
                                  ),
                                  onPressed: _launchPayPalPayment,
                                ),
                              ),
                              const SizedBox(height: 10),

                              SizedBox(
                                width: double.infinity,
                                child: OutlinedButton.icon(
                                  style: OutlinedButton.styleFrom(
                                    foregroundColor: Colors.greenAccent,
                                    side: const BorderSide(color: Colors.greenAccent),
                                    padding: const EdgeInsets.symmetric(vertical: 10),
                                    shape: RoundedRectangleBorder(
                                      borderRadius: BorderRadius.circular(10),
                                    ),
                                  ),
                                  icon: _isVerifyingPayment
                                      ? const SizedBox(
                                          width: 14,
                                          height: 14,
                                          child: CircularProgressIndicator(
                                              strokeWidth: 2, color: Colors.greenAccent),
                                        )
                                      : const Icon(Icons.check_circle_outline, color: Colors.greenAccent),
                                  label: const Text(
                                    "J'ai payé, Débloquer à vie",
                                    style: TextStyle(fontWeight: FontWeight.bold, fontSize: 12),
                                  ),
                                  onPressed: _isVerifyingPayment ? null : _autoActivateAfterPayment,
                                ),
                              ),
                              const SizedBox(height: 12),
                              const Divider(color: Colors.white12),
                              const SizedBox(height: 8),
                            ],

                            Container(
                              padding: const EdgeInsets.all(6),
                              decoration: BoxDecoration(
                                color: Colors.white,
                                borderRadius: BorderRadius.circular(10),
                              ),
                              child: Image.network(
                                "https://api.qrserver.com/v1/create-qr-code/?size=150x150&data=${Uri.encodeComponent(_paypalLink)}",
                                width: 100,
                                height: 100,
                                errorBuilder: (_, __, ___) => const Icon(Icons.qr_code, size: 80, color: Colors.black),
                              ),
                            ),
                            const SizedBox(height: 10),

                            InkWell(
                              onTap: () {
                                Clipboard.setData(ClipboardData(text: _paypalLink));
                                ScaffoldMessenger.of(context).showSnackBar(
                                  const SnackBar(content: Text("Lien PayPal copié !"), duration: Duration(seconds: 1)),
