import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:url_launcher/url_launcher.dart';
import '../services/activation_service.dart';
import 'login_screen.dart';
import 'home_screen.dart';
import 'shared_prefs_helper.dart';

class DeviceInfoScreen extends StatefulWidget {
  const DeviceInfoScreen({super.key});

  @override
  State<DeviceInfoScreen> createState() => _DeviceInfoScreenState();
}

class _DeviceInfoScreenState extends State<DeviceInfoScreen> {
  String _deviceId = "Chargement...";
  String _networkSignature = "Chargement...";
  int _daysRemaining = 5;
  String _expirationDateStr = "Chargement...";
  bool _isActivated = false;
  bool _isTrial = true;
  bool _isLoading = true;
  bool _isVerifyingPayment = false;

  // Lien PayPal Pro configuré avec ton adresse e-mail exacte
  final String _paypalLink = "https://www.paypal.com/paypalme/teddyjacquet";

  final TextEditingController _keyController = TextEditingController();
  String _message = '';

  @override
  void initState() {
    super.initState();
    _loadInfo();
  }

  Future<void> _loadInfo() async {
    String devId = await ActivationService.getDeviceId();
    String netSig = await ActivationService.getNetworkSignature();
    var status = await ActivationService.checkAccessStatus();

    int daysLeft = status['days_remaining'] ?? 5;
    bool activated = status['reason'] == 'ACTIVATED';
    bool trial = status['reason'] == 'IN_TRIAL' || !activated;

    DateTime now = DateTime.now();
    DateTime expirationDate = now.add(Duration(days: daysLeft));
    String formattedDate =
        "${expirationDate.day.toString().padLeft(2, '0')}/${expirationDate.month.toString().padLeft(2, '0')}/${expirationDate.year}";

    setState(() {
      _deviceId = devId.length > 12 ? devId.substring(0, 12).toUpperCase() : devId.toUpperCase();
      _networkSignature = netSig.length > 10 ? netSig.substring(0, 10).toUpperCase() : netSig.toUpperCase();
      _daysRemaining = daysLeft;
      _isActivated = activated;
      _isTrial = trial;
      _expirationDateStr = _isActivated ? "Illimité (Accès à vie)" : formattedDate;
      _isLoading = false;
    });
  }

  /// Ouvre le navigateur sur la page de paiement PayPal
  Future<void> _launchPayPalPayment() async {
    final Uri url = Uri.parse(_paypalLink);
    if (!await launchUrl(url, mode: LaunchMode.externalApplication)) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text("Impossible d'ouvrir le navigateur.")),
        );
      }
    }
  }

  /// Déblocage automatique après confirmation du paiement par le client
  Future<void> _autoActivateAfterPayment() async {
    setState(() {
      _isVerifyingPayment = true;
      _message = "Vérification du paiement en cours...";
    });

    String devId = await ActivationService.getDeviceId();
    String autoGeneratedKey = ActivationService.generateLicenseKeyForDevice(devId);
    bool success = await ActivationService.activateLicense(autoGeneratedKey);

    await Future.delayed(const Duration(seconds: 1));

    if (mounted) {
      if (success) {
        setState(() {
          _isActivated = true;
          _isTrial = false;
          _isVerifyingPayment = false;
          _expirationDateStr = "Illimité (Accès à vie)";
          _message = "Félicitations ! Votre licence à vie a été activée automatiquement !";
        });
      } else {
        setState(() {
          _isVerifyingPayment = false;
          _message = "Échec de l'activation automatique. Veuillez réessayer.";
        });
      }
    }
  }

  void _verifyAndActivate() async {
    bool success = await ActivationService.activateLicense(_keyController.text);
    if (success) {
      setState(() {
        _isActivated = true;
        _isTrial = false;
        _expirationDateStr = "Illimité (Accès à vie)";
        _message = "Application activée avec succès à vie !";
      });
    } else {
      setState(() {
        _message = "Clé d'activation invalide.";
      });
    }
  }

  void _proceedToApp() async {
    final accounts = await SharedPrefsHelper.getAccounts();
    if (!mounted) return;

    if (accounts.isNotEmpty) {
      final activeAccount = accounts.first;
      Navigator.pushReplacement(
        context,
        MaterialPageRoute(
          builder: (_) => HomeScreen(
            serverUrl: activeAccount.serverUrl,
            username: activeAccount.username,
            password: activeAccount.password,
          ),
        ),
      );
    } else {
      Navigator.pushReplacement(
        context,
        MaterialPageRoute(builder: (_) => const LoginScreen()),
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    bool isAccountActive = _isActivated || _isTrial;

    return Scaffold(
      backgroundColor: const Color(0xFF0B101D),
      appBar: AppBar(
        backgroundColor: Colors.transparent,
        elevation: 0,
        title: const Text("Informations de Licence & Paiement"),
      ),
      body: _isLoading
          ? const Center(child: CircularProgressIndicator(color: Colors.cyanAccent))
          : SingleChildScrollView(
              padding: const EdgeInsets.all(20.0),
              child: Column(
                children: [
                  // CARTE STATUT & INFOS APPAREIL
                  Container(
                    padding: const EdgeInsets.all(20),
                    decoration: BoxDecoration(
                      color: const Color(0xFF131B2E),
                      borderRadius: BorderRadius.circular(16),
                      border: Border.all(color: Colors.white12),
                    ),
                    child: Column(
                      children: [
                        Row(
                          mainAxisAlignment: MainAxisAlignment.center,
                          children: [
                            const Text("Statut : ",
                                style: TextStyle(fontSize: 16, color: Colors.white)),
                            Container(
                              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 4),
                              decoration: BoxDecoration(
                                color: isAccountActive
                                    ? Colors.green.withOpacity(0.2)
                                    : Colors.red.withOpacity(0.2),
                                borderRadius: BorderRadius.circular(20),
                                border: Border.all(
                                    color: isAccountActive
                                        ? Colors.greenAccent
                                        : Colors.redAccent),
                              ),
                              child: Text(
                                _isActivated
                                    ? "ACTIF (À VIE)"
                                    : (_isTrial ? "ESSAI GRATUIT" : "INACTIF"),
                                style: TextStyle(
                                  color: isAccountActive
                                      ? Colors.greenAccent
                                      : Colors.redAccent,
                                  fontWeight: FontWeight.bold,
                                  fontSize: 13,
                                ),
                              ),
                            ),
                          ],
                        ),
                        const SizedBox(height: 16),
                        Row(
                          mainAxisAlignment: MainAxisAlignment.spaceBetween,
                          children: [
                            const Text("Essai restant :",
                                style: TextStyle(color: Colors.white70, fontSize: 14)),
                            Text(
                              _isActivated ? "Illimité" : "$_daysRemaining jour(s)",
                              style: const TextStyle(
                                color: Colors.amber,
                                fontWeight: FontWeight.bold,
                                fontSize: 14,
                              ),
                            ),
                          ],
                        ),
                        const SizedBox(height: 8),
                        Row(
                          mainAxisAlignment: MainAxisAlignment.spaceBetween,
                          children: [
                            const Text("Expiration :",
                                style: TextStyle(color: Colors.white70, fontSize: 14)),
                            Text(
                              _expirationDateStr,
                              style: TextStyle(
                                color: _isActivated ? Colors.greenAccent : Colors.amber,
                                fontWeight: FontWeight.bold,
                                fontSize: 14,
                              ),
                            ),
                          ],
                        ),
                        const Divider(color: Colors.white12, height: 20),
                        const Text("Identifiant Appareil (Android ID)",
                            style: TextStyle(
                                color: Colors.white,
                                fontSize: 14,
                                fontWeight: FontWeight.bold)),
                        const SizedBox(height: 4),
                        Row(
                          mainAxisAlignment: MainAxisAlignment.center,
                          children: [
                            Text(_deviceId,
                                style: const TextStyle(
                                    color: Colors.amber,
                                    fontSize: 16,
                                    fontWeight: FontWeight.bold)),
                            const SizedBox(width: 8),
                            InkWell(
                              onTap: () {
                                Clipboard.setData(ClipboardData(text: _deviceId));
                                ScaffoldMessenger.of(context).showSnackBar(
                                  const SnackBar(
                                      content: Text("ID copié !"),
                                      duration: Duration(seconds: 1)),
                                );
                              },
                              child: const Icon(Icons.copy,
                                  size: 16, color: Colors.white54),
                            ),
                          ],
                        ),
                      ],
                    ),
                  ),
                  const SizedBox(height: 20),

                  // CARTE PAIEMENT / ACTIVATION
                  if (!_isActivated) ...[
                    Container(
                      padding: const EdgeInsets.all(20),
                      decoration: BoxDecoration(
                        color: const Color(0xFF131B2E),
                        borderRadius: BorderRadius.circular(16),
                        border: Border.all(color: Colors.cyanAccent.withOpacity(0.3)),
                      ),
                      child: Column(
                        children: [
                          const Icon(Icons.verified_rounded, size: 36, color: Colors.cyanAccent),
                          const SizedBox(height: 8),
                          const Text(
                            "Licence à Vie : 5,00 €",
                            style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: Colors.amber),
                          ),
                          const SizedBox(height: 6),
                          const Text(
                            "Payez directement en ligne via PayPal.",
                            textAlign: TextAlign.center,
                            style: TextStyle(color: Colors.grey, fontSize: 12),
                          ),
                          const SizedBox(height: 16),
                          SizedBox(
                            width: double.infinity,
                            child: ElevatedButton.icon(
                              style: ElevatedButton.styleFrom(
                                backgroundColor: const Color(0xFFFFC439),
                                foregroundColor: Colors.black,
                                padding: const EdgeInsets.symmetric(vertical: 12),
                                shape: RoundedRectangleBorder(
                                  borderRadius: BorderRadius.circular(10),
                                ),
                              ),
                              icon: const Icon(Icons.payment, color: Colors.black),
                              label: const Text(
                                "PAYER 5,00 € VIA PAYPAL",
                                style: TextStyle(fontWeight: FontWeight.bold, fontSize: 13),
                              ),
                              onPressed: _launchPayPalPayment,
                            ),
                          ),
                          const SizedBox(height: 10),
                          SizedBox(
                            width: double.infinity,
                            child: OutlinedButton.icon(
                              style: OutlinedButton.styleFrom(
                                foregroundColor: Colors.greenAccent,
                                side: const BorderSide(color: Colors.greenAccent),
                                padding: const EdgeInsets.symmetric(vertical: 10),
                                shape: RoundedRectangleBorder(
                                  borderRadius: BorderRadius.circular(10),
                                ),
                              ),
                              icon: _isVerifyingPayment
                                  ? const SizedBox(
                                      width: 14,
                                      height: 14,
                                      child: CircularProgressIndicator(
                                          strokeWidth: 2, color: Colors.greenAccent),
                                    )
                                  : const Icon(Icons.check_circle_outline, color: Colors.greenAccent),
                              label: const Text(
                                "J'ai payé, Débloquer à vie",
                                style: TextStyle(fontWeight: FontWeight.bold, fontSize: 12),
                              ),
                              onPressed: _isVerifyingPayment ? null : _autoActivateAfterPayment,
                            ),
                          ),
                        ],
                      ),
                    ),
                    const SizedBox(height: 20),
                  ],

                  // BOUTONS DE NAVIGATION
                  Row(
                    mainAxisAlignment: MainAxisAlignment.center,
                    children: [
                      ElevatedButton(
                        style: ElevatedButton.styleFrom(
                          backgroundColor: const Color(0xFF1E293B),
                          foregroundColor: Colors.white,
                          padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 12),
                        ),
                        onPressed: _loadInfo,
                        child: const Text("RECHARGER"),
                      ),
                      const SizedBox(width: 16),
                      ElevatedButton(
                        style: ElevatedButton.styleFrom(
                          backgroundColor: const Color(0xFF1E293B),
                          foregroundColor: Colors.white,
                          padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 12),
                        ),
                        onPressed: _proceedToApp,
                        child: const Text("CONTINUER"),
                      ),
                    ],
                  ),
                  if (_message.isNotEmpty) ...[
                    const SizedBox(height: 16),
                    Text(
                      _message,
                      textAlign: TextAlign.center,
                      style: TextStyle(
                        color: _isActivated ? Colors.greenAccent : Colors.amber,
                        fontWeight: FontWeight.bold,
                      ),
                    ),
                  ],
                ],
              ),
            ),
    );
  }
}